-- ProCal: схема Supabase (бесплатный тариф). Запустить в SQL Editor.

create table if not exists public.meals (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  device_id text,
  name text not null,
  kcal integer not null,
  protein integer not null default 0,
  carbs integer not null default 0,
  fat integer not null default 0
);

create table if not exists public.feedback (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  device_id text,
  kind text not null check (kind in ('up', 'down')),
  meal_name text,
  kcal integer,
  coach text
);

-- Сервер пишет сервисным ключом (SUPABASE_SERVICE_ROLE_KEY), он RLS обходит.
-- RLS включаем, чтобы anon-ключ с клиентом не мог читать/писать напрямую.
alter table public.meals enable row level security;
alter table public.feedback enable row level security;

-- Полезные индексы
create index if not exists meals_device_idx on public.meals (device_id, created_at desc);
create index if not exists feedback_created_idx on public.feedback (created_at desc);
